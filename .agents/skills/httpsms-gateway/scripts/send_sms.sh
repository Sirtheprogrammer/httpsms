#!/usr/bin/env bash
#
# send_sms.sh - Send an SMS message through HttpSMS Gateway
# Usage: ./send_sms.sh -t "+15551234567" -m "Hello from HttpSMS" [-s 0] [-k TOKEN] [-u URL]
#

set -euo pipefail

BASE_URL="${HTTPSMS_BASE_URL:-http://localhost:8080}"
API_KEY="${HTTPSMS_API_KEY:-htsms_live_mcp_test_token_20261024_secret}"
SIM_SLOT=0
RECIPIENT=""
MESSAGE=""
DEVICE_ID=""
IDEMPOTENCY_KEY=""

usage() {
  cat <<EOF
Usage: $0 -t <recipient> -m <message> [options]

Required:
  -t, --to        Destination phone number in E.164 format (e.g. +15551234567)
  -m, --message   Text message body

Options:
  -s, --slot      SIM slot index (0 or 1, default: 0)
  -d, --device    Target device UUID (optional)
  -i, --idemp     Idempotency key (optional, random UUID generated by default)
  -k, --key       API Bearer Token (default: env HTTPSMS_API_KEY)
  -u, --url       Gateway Base URL (default: env HTTPSMS_BASE_URL or http://localhost:8080)
  -h, --help      Show this help message
EOF
  exit 1
}

while [[ $# -gt 0 ]]; do
  case $1 in
    -t|--to)
      RECIPIENT="$2"
      shift 2
      ;;
    -m|--message)
      MESSAGE="$2"
      shift 2
      ;;
    -s|--slot)
      SIM_SLOT="$2"
      shift 2
      ;;
    -d|--device)
      DEVICE_ID="$2"
      shift 2
      ;;
    -i|--idemp)
      IDEMPOTENCY_KEY="$2"
      shift 2
      ;;
    -k|--key)
      API_KEY="$2"
      shift 2
      ;;
    -u|--url)
      BASE_URL="$2"
      shift 2
      ;;
    -h|--help)
      usage
      ;;
    *)
      echo "Error: Unknown argument $1"
      usage
      ;;
  esac
done

if [[ -z "$RECIPIENT" || -z "$MESSAGE" ]]; then
  echo "Error: Both --to (-t) and --message (-m) are required."
  usage
fi

if [[ -z "$IDEMPOTENCY_KEY" ]]; then
  IDEMPOTENCY_KEY="cli_$(date +%s)_$RANDOM"
fi

# Build JSON Payload
PAYLOAD=$(cat <<EOF
{
  "recipient": "$RECIPIENT",
  "body": $(printf '%s' "$MESSAGE" | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))'),
  "sim_slot": $SIM_SLOT,
  "idempotency_key": "$IDEMPOTENCY_KEY"$(if [[ -n "$DEVICE_ID" ]]; then echo ",\"device_id\":\"$DEVICE_ID\""; fi)
}
EOF
)

echo "Dispatched request to $BASE_URL/api/v1/sms/send:"
curl -s -X POST "$BASE_URL/api/v1/sms/send" \
  -H "Authorization: Bearer $API_KEY" \
  -H "Content-Type: application/json" \
  -d "$PAYLOAD" | python3 -m json.tool || echo ""
